"""Write references/sanity_check_4.md: counts + 10 verification rows per label source, each shown next to the raw text
re-read from the saved source file (so the check is independent of the parsed table).

Run: /usr/local/bin/python3 scripts/sanity_check_4.py     (no network)
"""
import sys, re, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import pandas as pd
from bs4 import BeautifulSoup
from parse_labels_s1 import cell_text, expand_rows, norm

ROOT = Path(__file__).resolve().parents[1]
RAW, PROC = ROOT / "data/raw/labels", ROOT / "data/processed/labels"
SEED = 7
md = []
w = md.append


def clip(s, n=320):
    s = re.sub(r"\s+", " ", str(s)).strip()
    return (s[:n] + " ...") if len(s) > n else s


def block(i, parsed: dict, raw: str, extra=""):
    w(f"**{i}.** " + "; ".join(f"`{k}` = {clip(v, 160)}" for k, v in parsed.items()))
    w(f"- raw text in saved file: {clip(raw)}")
    if extra: w(f"- {extra}")
    w("")


# ---------------- Source 1 ----------------
s1 = pd.read_csv(PROC / "s1_signals.csv", keep_default_na=False)
new8 = ["2016Q3", "2016Q4", "2017Q1", "2017Q3", "2017Q4", "2018Q1", "2018Q2", "2018Q3"]
rep = json.load(open(PROC / "s1_parse_report.json"))
w("# Sanity check 4: confirmation-label sources (collection only; nothing matched to drug-event pairs, no target built)\n")
w("Generated by `scripts/sanity_check_4.py` from the saved files in `data/raw/labels/` (no network). Notes on rules/robots: `references/labels_collection_notes.md`.\n")
w("## Source 1: FDA Section 921 potential-signal postings\n")
w(f"- Rows: **{len(s1)}** over **{s1.posting_quarter.nunique()}** quarters ({s1.posting_quarter.min()} to {s1.posting_quarter.max()}). "
  f"Live fda.gov: {int((s1.snapshot_date == '').sum())} rows; web.archive.org snapshots: {int((s1.snapshot_date != '').sum())} rows (`snapshot_date` + `source_url` on every row).")
w(f"- outcome_class: {s1.outcome_class.value_counts().to_dict()}; distinct raw action strings: {s1.fda_action_raw.nunique()}")
w("- The 8 in-window quarters re-fetched from web.archive.org (rows, snapshot date, page 'as of' date):\n")
w("| quarter | rows | snapshot_date | as-of date in page header | snapshot URL |\n|---|---|---|---|---|")
for q in new8:
    g = s1[s1.posting_quarter == q]
    w(f"| {q} | {len(g)} | {g.snapshot_date.iloc[0]} | {g.action_asof_date_raw.iloc[0]} | {g.source_url.iloc[0][:110]}... |")
w("")
skipped = [x for x in rep["skipped"] if x[1] != "quarantined_robots_disallowed"]
q_unparsed = sorted({x[0] for x in rep["skipped"] if x[1] == "quarantined_robots_disallowed"})
w(f"- Never parsed/used (robots-disallowed archive-it copies, pre-2016 or 2015Q4): {', '.join(q_unparsed)}. Other parse skips: {skipped or 'none'}")
w("- Pages with no index entry (not fabricated): 2010Q2, 2012Q3, 2014Q1, 2015Q1.\n")
w("### 10 verification rows (5 from the re-fetched quarters, 5 from others)\n")
rs = pd.concat([s1[s1.posting_quarter.isin(new8)].sample(5, random_state=SEED), s1[~s1.posting_quarter.isin(new8)].sample(5, random_state=SEED)])
for i, (_, r) in enumerate(rs.iterrows(), 1):
    soup = BeautifulSoup((ROOT / r.source_file).read_text(encoding="utf-8", errors="replace"), "html.parser")
    raw = ""
    for tab in (soup.find("main") or soup).find_all("table"):
        trs = tab.find_all("tr")
        for cells, inh in expand_rows(trs):
            if len(cells) >= 3 and cells[0] == r.drug_name_raw and cells[1] == r.potential_signal_raw and cells[2] == r.fda_action_raw:
                raw = " || ".join(cells[:3]); break
        if raw: break
    block(i, dict(quarter=r.posting_quarter, drug_name_raw=r.drug_name_raw, potential_signal_raw=r.potential_signal_raw,
                  outcome_class=r.outcome_class, outcome_matches=r.outcome_matches, snapshot_date=r.snapshot_date or "live",
                  action_asof_date_raw=r.action_asof_date_raw), raw or "NOT FOUND IN SAVED FILE",
          f"`fda_action_raw` = {clip(r.fda_action_raw, 300)}<br>source: {r.source_url}")

# ---------------- Source 2 ----------------
c = pd.read_csv(PROC / "s2_probe_counts.csv")
rows = pd.read_csv(PROC / "s2_probe_rows.csv", keep_default_na=False)
w("## Source 2: SrLC (probe only; the full scrape has NOT been run)\n")
w("Queries ran inside the 23:00-05:00 EDT window with a 30 s delay (log: all `accepted` = True means the server did not bounce the form).\n")
m16 = c[c.tag.str.match(r"2016-\d\d")]; m25 = c[c.tag.str.match(r"2025-\d\d")]
w(f"- 2016 monthly rows: {m16.n_rows.tolist()} (sum {m16.n_rows.sum()}; year query {int(c[c.tag=='year2016'].n_rows.iloc[0])}); 2025 monthly rows: {m25.n_rows.tolist()} (sum {m25.n_rows.sum()}; year query {int(c[c.tag=='year2025'].n_rows.iloc[0])}).")
yr = c[c.tag.str.startswith("year")]
w(f"- Year queries 2016..2026: {dict(zip(yr.tag.str[4:], yr.n_rows))}; sum {yr.n_rows.sum()} = full-range query {int(c[c.tag.str.startswith('full')].n_rows.iloc[0])}. Max single-query rows: {c.n_rows.max()} (no round-number plateau, monthly and yearly sums agree, so no evidence of a result cap).")
full = rows[rows.tag.str.startswith("full")]
w(f"- Unique detail links (DrugNameID) over 2016-01-01..2026-10-07: **{full.detail_href.nunique()}** (rows {len(full)}; distinct drug names {full.drug_name.nunique()}; distinct application numbers {full.application_number.nunique()}).\n")
w("### 10 verification rows (list table: parsed vs raw `<tr>` text in the saved query page)\n")
smp = full.sample(10, random_state=SEED)
for i, (_, r) in enumerate(smp.iterrows(), 1):
    soup = BeautifulSoup((ROOT / r.source_file).read_text(encoding="utf-8", errors="replace"), "html.parser")
    raw = ""
    for tr in soup.find(id="example").find_all("tr"):
        a = tr.find("a", href=True)
        if a and a["href"] == r.detail_href: raw = " | ".join(norm(td.get_text(" ")) for td in tr.find_all("td")); break
    block(i, dict(drug_name=r.drug_name, active_ingredient=r.active_ingredient, application_number=r.application_number,
                  application_type=r.application_type, supplement_date=r.supplement_date, database_updated=r.database_updated),
          raw or "NOT FOUND", f"detail link: {r.detail_href}")
w("### Detail pages fetched (5)\n")
w("| DrugNameID | drug | size KB | supplements on page | headings seen after 'Download Data' |\n|---|---|---|---|---|")
for f in sorted(RAW.glob("s2_detail_*.html")):
    did = f.stem.split("_")[-1]
    soup = BeautifulSoup(f.read_text(encoding="utf-8", errors="replace"), "html.parser")
    t = (soup.find(id="content") or soup).get_text("\n", strip=True); t = t[t.find("Download Data"):]
    name = t.split("\n")[1] if "\n" in t else ""
    head = (soup.find(id="content") or soup).get_text("\n", strip=True)
    nm = re.search(r"Close\n([^\n]+)\n\(([A-Z]+-\d+)\)", head)
    sup = re.findall(r"(\d\d/\d\d/\d{4})\n\(([A-Z]+-\d+)\)", t)
    secs = sorted({l for l in t.split("\n") if re.match(r"^(Boxed Warning|Contraindications|Warnings and Precautions|Warnings|Precautions|Adverse Reactions|Drug Interactions|Use in Specific Populations|Patient Counseling Information|Patient Information|Medication Guide)$", l.strip())})
    w(f"| {did} | {nm.group(1) if nm else '?'} {nm.group(2) if nm else ''} | {f.stat().st_size // 1024} | {len(sup)} ({', '.join(d for d, _ in sup[:4])}) | {', '.join(secs) or '(section heading appears as e.g. numbered text, see raw)'} |")
w("")

# ---------------- Source 3 ----------------
d = pd.read_csv(PROC / "s3_dsc_index.csv", keep_default_na=False)
w("## Source 3: FDA Drug Safety Communications (DSC)\n")
w(f"- Index rows: **{len(d)}** ({d.dsc_date.min()} to {d.dsc_date.max()}); by year: {d.groupby(d.dsc_date.str[:4]).size().to_dict()}.")
w(f"- Rows listed in two indexes (same date+title): {int(d.duplicated(['dsc_date','title_raw']).sum())} (page fetched once).")
have = d.page_file.map(lambda p: (ROOT / p).exists())
w(f"- DSC pages saved: {int(have.sum())} of {int((~d.duplicated(['dsc_date','title_raw'])).sum())} unique.")
w("- Coverage limit: FDA says DSCs later superseded were archived off these lists, so 2016-2019 counts are lower bounds. Pre-2020 entries come from web.archive.org snapshots (2018-12-07, 2019-02-07, 2020-01-09); 2020+ from live fda.gov.\n")
w("### 10 verification rows (index entry vs raw index text vs fetched page title)\n")
smp = d.sample(10, random_state=SEED)
for i, (_, r) in enumerate(smp.iterrows(), 1):
    soup = BeautifulSoup((ROOT / r.source_file).read_text(encoding="utf-8", errors="replace"), "html.parser")
    raw = ""
    for a in soup.find_all("a", href=True):
        if norm(a.get_text(" ")) == r.title_raw:
            par = a.find_parent(["tr", "li"]); raw = norm(par.get_text(" ")) if par else ""; break
    pg = ROOT / r.page_file
    if not pg.exists():   # duplicate listing: page saved under the first listing's URL
        alt = d[(d.dsc_date == r.dsc_date) & (d.title_raw == r.title_raw)].page_file.tolist()
        pg = next((ROOT / p for p in alt if (ROOT / p).exists()), pg)
    ptitle = ""
    if pg.exists():
        ps = BeautifulSoup(pg.read_text(encoding="utf-8", errors="replace"), "html.parser")
        h1 = ps.find("h1"); ptitle = norm(h1.get_text(" ")) if h1 else norm(ps.title.get_text()) if ps.title else ""
    block(i, dict(dsc_date_raw=r.dsc_date_raw, dsc_date=r.dsc_date, title_raw=r.title_raw, snapshot_date=r.snapshot_date or "live"),
          raw or "NOT FOUND", f"fetched page heading: {clip(ptitle, 200) or '(page not saved)'}  | title matches: {'YES' if ptitle and (r.title_raw[:40].lower() in ptitle.lower() or ptitle.lower()[:40] in r.title_raw.lower()) else 'check'}<br>url: {r.dsc_url}")

(ROOT / "references/sanity_check_4.md").write_text("\n".join(md) + "\n")
print("written", len("\n".join(md)), "chars")
